"""Write the plot mine's pithead (spec.py, the building skill, every region's look) into the add-on.

    python3 export.py        -> ../../../Siege_Nights_BP/scripts/plotcaves/pithead_data.js

Same data shape and frame as export_halls.py: the front row is z = 0 (towards the Plot Stone), +z runs in, x = 0 the
middle, y = 0 the ground. The shaft's middle is the mark "shaft" (the game puts it on the plot's shaft). The shaft's
own cells and its ladder are left out: the game's nightly plan writes them (Siege_Nights_BP/scripts/plotcaves).
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, ".."))
import spec as pit  # noqa: E402
SKILL = os.path.join(pit.SKILL, "scripts")
if SKILL not in sys.path: sys.path.insert(0, SKILL)
from bp import Blueprint  # noqa: E402
from export_halls import export  # noqa: E402
import engine  # noqa: E402

DEST = os.path.join(HERE, "..", "..", "..", "Siege_Nights_BP", "scripts", "plotcaves", "pithead_data.js")


def blueprint(region):
    bp = Blueprint(f"pithead_{region}"); bp.marks = {"shaft": (0, 0, 0)}
    engine.into_blueprint(bp, pit.specs(False, pit.SKILL, (region,))[f"pithead_{region}"])
    bp.markers["door"] = (0, 1, pit.PLOT[3])           # the front edge's middle, towards the Plot Stone
    return bp.finish()


def main():
    out, problems = {}, []
    for region in pit.ORDER:
        d = export(blueprint(region))
        if d["marks"]["shaft"] != [0, 0, pit.PLOT[3] + 1]: problems.append(f"{region}: shaft mark at {d['marks']['shaft']}")
        b = d["box"]
        if (b["x1"] - b["x0"]) % 2 or (b["z1"] - b["z0"]) % 2: problems.append(f"{region}: even footprint {b}")
        out[region] = d
        print(region, "cells", sum(r[3] for r in d["rows"]), "box", d["box"])
    js = ("// Generated by map/structures/pithead/export.py from pithead/spec.py (the building skill). Do not edit by hand.\n"
          "// The plot mine's pithead per region: palette [id, logical props], rows [y, z, x0, count, palette index], the front\n"
          "// row (towards the Plot Stone) at z = 0, x = 0 the middle, y = 0 the ground; marks.shaft is the shaft's middle.\n"
          "export const PITHEADS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    open(DEST, "w").write(js)
    print("wrote", os.path.normpath(DEST), round(len(js) / 1e3), "KB")
    if problems: print("PROBLEMS:\n  " + "\n  ".join(problems)); sys.exit(1)


if __name__ == "__main__":
    main()
