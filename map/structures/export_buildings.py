"""Write the nine plot buildings, in each region's style, into the add-on for the settlement build engine.

    python3 export_buildings.py        -> ../../Siege_Nights_BP/scripts/settle/designs_data.js

Same data shape and frame as export_halls.py (the Foundation Stone at (0, 1, 0) in front of the door,
+z into the building); settle/buildings.js lays it into a Plan with townhall/designs.js drawData.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import settle_buildings as SB
import settle_skill as SK
from export_halls import export

LIBRARY_MARKS = {f"shelf{i}" for i in range(16)} | {"lectern", "portrait0", "portrait1", "portrait2", "painting0"}
SIDE, DEEP = 8, 14   # keep every plot building small enough for a settlement plot (Large 15 x 15)
PLOT_WIDE = {"house": 11, "farmhouse": 11, "mint": 11, "townhouse": 13}   # Medium and long Medium plots are narrower

def on_stone(d):
    return any(z == 0 and y in (1, 2) and x0 <= 0 < x0 + n for y, z, x0, n, i in d["rows"])

def drop_stone_air(d):
    """Air the design clears on the Foundation Stone's own spot is left out (the stone stays till the end)."""
    rows = []
    for r in d["rows"]:
        y, z, x0, n, i = r
        if z == 0 and y in (1, 2) and x0 <= 0 < x0 + n and d["palette"][i][0] == "minecraft:air":
            if x0 < 0: rows.append([y, z, x0, -x0, i])
            if x0 + n > 1: rows.append([y, z, 1, x0 + n - 1, i])
        else: rows.append(r)
    return rows

def main():
    out, problems = {}, []
    for region in SB.REGIONS:
        out[region] = {}
        makers = dict(SB.BUILDERS)   # plus the plot buildings drawn on the building skill, where the region has a spec
        makers.update({b: (lambda r, b=b: SK.build(b, r)) for b in SK.IDS if SK.has(b, region)})
        for name, make in makers.items():
            bp = make(region)
            for _ in range(4):   # move the Foundation Stone out until nothing of the building stands on or before it
                d = export(bp)
                d["rows"] = drop_stone_air(d)
                if d["box"]["z0"] >= 0 and not on_stone(d): break
                x, y, z = bp.markers["door"]; bp.markers["door"] = (x, y, z + 1)
            out[region][name] = d; b = d["box"]
            if on_stone(d): problems.append(f"{region} {name}: blocks where the Foundation Stone stands")
            if max(-b["x0"], b["x1"]) > SIDE or b["z1"] > DEEP or b["z0"] < 0:
                problems.append(f"{region} {name}: too big {b}")
            if name in PLOT_WIDE and b["x1"] - b["x0"] + 1 > PLOT_WIDE[name]:
                problems.append(f"{region} {name}: wider than its plot ({b['x1'] - b['x0'] + 1} > {PLOT_WIDE[name]})")
            if name == "library" and LIBRARY_MARKS - set(d["marks"]):
                problems.append(f"{region} library: missing marks {sorted(LIBRARY_MARKS - set(d['marks']))}")
            print(region, name, "cells", sum(r[3] for r in d["rows"]), "box", b)
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "settle", "designs_data.js")
    js = ("// Generated by map/structures/export_buildings.py from settle_buildings.py. Do not edit by hand.\n"
          "// The plot buildings in each region's style: palette [id, logical props], rows [y, z, x0, count, palette index].\n"
          "export const BUILDING_DESIGNS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    open(dest, "w").write(js)
    print("wrote", os.path.normpath(dest), round(len(js) / 1e3), "KB")
    # the Stables (three levels) and the Breeder's Yard, raised by horses/barn.js
    barns = {}
    for region in SB.REGIONS:
        barns[region] = {}
        prev = None
        for name, make in SB.HORSE_BUILDERS.items():
            d = export(make(region)); d["rows"] = drop_stone_air(d); barns[region][name] = d; b = d["box"]
            if on_stone(d): problems.append(f"{region} {name}: blocks where the Stables block stands")
            wide = 11 if name.startswith("stables_") else 8   # the Barn plot is 23 x 13 with the eaves (2026-11-14)
            if b["z0"] < 0 or max(-b["x0"], b["x1"]) > wide or (name.startswith("stables_") and b["z1"] > 12):
                problems.append(f"{region} {name}: box {b}")
            if name.startswith("stables_") and prev and not (b["x0"] <= prev["x0"] and b["x1"] >= prev["x1"] and b["z1"] >= prev["z1"]):
                problems.append(f"{region} {name} does not contain the level before")
            if name.startswith("stables_"): prev = b
            print(region, name, "box", b)
    # the Dragon Stable (Emberwaste only: dragons are the Emberwaste's), raised by the Dragon Roost (settle/blockdesigns.js)
    import dragon_stable_skill as DS
    d = export(DS.build()); d["rows"] = drop_stone_air(d); b = d["box"]
    barns["emberwaste"]["dragon_stable"] = d
    if on_stone(d): problems.append("dragon_stable: blocks where the Dragon Roost stands")
    if b["z0"] < 0 or (b["x1"] - b["x0"] + 1) % 2 == 0 or max(-b["x0"], b["x1"]) > 15 or b["z1"] > 20:
        problems.append(f"dragon_stable: box {b}")
    print("emberwaste dragon_stable box", b)
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "settle", "barn_data.js")
    open(dest, "w").write("// Generated by map/structures/export_buildings.py from settle_buildings.py. Do not edit by hand.\n"
                          "// The Stables at levels 1-3 and the Breeder's Yard in each region's style, same shape as designs_data.js:\n"
                          "// the Stables block / Breeder's Post at (0, 1, 0), +z into the building. Draw with townhall/designs.js drawData.\n"
                          "export const BARN_DESIGNS = " + json.dumps(barns, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(dest))
    # the Storehouse at its four levels (one per town tier), raised and rebuilt by settle/storehouse.js on the
    # starter village's 15 x 15 Storehouse ground
    import storehouse_skill as SS
    stores = {}
    for region in SS.REGIONS:
        stores[region] = {}
        last = 0
        for level in SS.LEVELS:
            bp = SS.build(level, region)
            for _ in range(4):
                d = export(bp); d["rows"] = drop_stone_air(d)
                if d["box"]["z0"] >= 0 and not on_stone(d): break
                x, y, z = bp.markers["door"]; bp.markers["door"] = (x, y, z + 1)
            n = SS.chests(bp); d["chests"] = n; b = d["box"]
            stores[region][f"storehouse_{level}"] = d
            if on_stone(d): problems.append(f"{region} storehouse {level}: blocks where the Foundation Stone stands")
            if max(-b["x0"], b["x1"]) > 7 or b["z1"] - b["z0"] + 1 > 15 or b["z0"] < 0:
                problems.append(f"{region} storehouse {level}: bigger than its 15 x 15 ground {b}")
            if n <= last: problems.append(f"{region} storehouse {level}: {n} chests, not more than level {level - 1} ({last})")
            if "goods" not in d["marks"]: problems.append(f"{region} storehouse {level}: no goods mark")
            last = n
            print(region, f"storehouse_{level}", "chests", n, "box", b)
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "settle", "storehouse_data.js")
    open(dest, "w").write("// Generated by map/structures/export_buildings.py from storehouse_skill.py. Do not edit by hand.\n"
                          "// The Storehouse at levels 1-4 (Hamlet, Town, City, Castle) in each region's style, same shape as designs_data.js\n"
                          "// plus chests (how many the level holds). Raised and rebuilt by settle/storehouse.js.\n"
                          "export const STOREHOUSE_DESIGNS = " + json.dumps(stores, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(dest))
    problems += wallwatch()
    if problems: print("PROBLEMS:\n  " + "\n  ".join(problems)); sys.exit(1)

def wallwatch():
    """The wall watchtower in each region (wallwatch_skill.py), raised astride the wall line by settle/walls.js.
    Its own file so it can be rewritten alone: python3 export_buildings.py wallwatch"""
    import wallwatch_skill as WW
    out, problems = {}, []
    for region in WW.REGIONS:
        d = export(WW.build(region)); b = d["box"]
        out[region] = d
        if "guard" not in d["marks"]: problems.append(f"{region} wallwatch: no guard mark")
        if (b["x1"] - b["x0"] + 1) % 2 == 0 or max(-b["x0"], b["x1"]) > 4 or b["z0"] < -1 or b["z1"] > 7:   # the roof eave may reach one over the door step
            problems.append(f"{region} wallwatch: box {b}")
        print(region, "wallwatch box", b, "guard", d["marks"].get("guard"))
    stands = {}
    for region in WW.REGIONS:   # the Low Palisade's lookout stand (Mateo 2026-11-14: the towers are too big for a level 1 wall)
        d = export(WW.build_stand(region)); b = d["box"]
        stands[region] = d
        if "guard" not in d["marks"]: problems.append(f"{region} wallstand: no guard mark")
        if max(-b["x0"], b["x1"]) > 1 or b["z0"] < 0 or b["z1"] > 3: problems.append(f"{region} wallstand: box {b}")
        print(region, "wallstand box", b, "guard", d["marks"].get("guard"))
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "settle", "wallwatch_data.js")
    open(dest, "w").write("// Generated by map/structures/export_buildings.py from wallwatch_skill.py. Do not edit by hand.\n"
                          "// The wall watchtower in each region's style, same shape as designs_data.js: the door's front step at (0, 1, 0),\n"
                          "// +z into the tower; marks.guard = where the lookout's guard stands. Raised by settle/walls.js (walldata.js watchSpots).\n"
                          "export const WALLWATCH_DESIGNS = " + json.dumps(out, separators=(",", ":")) + ";\n"
                          "// The lookout stand that stands in for the tower on the Low Palisade (wall level 1), same frame.\n"
                          "export const WALLSTAND_DESIGNS = " + json.dumps(stands, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(dest))
    return problems

if __name__ == "__main__":
    if sys.argv[1:] == ["wallwatch"]:
        p = wallwatch()
        if p: print("PROBLEMS:\n  " + "\n  ".join(p)); sys.exit(1)
    else:
        main()
