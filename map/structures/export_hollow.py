"""Write the Hollow's buildings (hollow_kit.py) into the add-on as data the game stamps over a few ticks.

    python3 export_hollow.py     -> ../../Siege_Nights_BP/scripts/hollowfolk/village_data.js

Unlike the town halls these never turn: offsets are world offsets from the site's centre (+x east,
+z south), y = 0 is the trodden ground layer, floors at y = 1. Blocks keep the logical form
(name + facing / axis / half ...); undertow/stamp.js spells the Bedrock states.
Rows are run-length coded along x: [y, z, x0, count, paletteIndex]. No air is written.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import hollow_kit as HK
from export_halls import KEEP

def export(bp, air=False):
    pal, idx, cells = [], {}, {}
    for (x, y, z), (n, p) in bp.cells.items():
        if n == "keep" or (n == "air" and not air): continue
        q = {k: v for k, v in p.items() if k in KEEP} if n != "air" else {}
        key = json.dumps([n, q], sort_keys=True)
        if key not in idx: idx[key] = len(pal); pal.append([n if ":" in n else "minecraft:" + n, q])
        cells[(x, y, z)] = idx[key]
    rows = []
    for (y, z) in sorted({(c[1], c[2]) for c in cells}):
        run = None
        for x in sorted(c[0] for c in cells if c[1] == y and c[2] == z):
            pi = cells[(x, y, z)]
            if run and run[2] + run[3] == x and run[4] == pi: run[3] += 1
            else:
                if run: rows.append(run)
                run = [y, z, x, 1, pi]
        if run: rows.append(run)
    xs = [c[0] for c in cells]; ys = [c[1] for c in cells]; zs = [c[2] for c in cells]
    box = {"x0": min(xs), "x1": max(xs), "y0": min(ys), "y1": max(ys), "z0": min(zs), "z1": max(zs)}
    return {"palette": pal, "rows": rows, "box": box}

# spots the village code needs clear on the floor (hollowfolk FOLK_SPOTS, the Tally block, the gates)
CLEAR = [(0, 1, 2), (-5, 1, 1), (4, 1, -1), (-11, 1, 9), (0, 1, 0), (0, 1, -13), (14, 1, 0)]

def main():
    out, problems = {}, []
    for i, vid in enumerate(HK.VILLAGES):
        bp = HK.village(vid, i)
        for p in CLEAR:
            if p in bp.cells and bp.cells[p][0] not in ("air", "keep"): problems.append(f"{vid}: {bp.cells[p][0]} at {p}")
        d = export(bp); out[vid] = d; b = d["box"]
        if b["x0"] < -16 or b["x1"] > 14 or b["z0"] < -13 or b["z1"] > 13 or b["y1"] > 11: problems.append(f"{vid}: too big {b}")
        print(vid, "cells", sum(r[3] for r in d["rows"]), "rows", len(d["rows"]), "box", b)
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "hollowfolk", "village_data.js")
    js = ("// Generated by map/structures/export_hollow.py from hollow_kit.py. Do not edit by hand.\n"
          "// The four mining villages: palette [id, logical props], rows [y, z, x0, count, palette index], world offsets.\n"
          "export const VILLAGE_DESIGNS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    open(dest, "w").write(js)
    print("wrote", os.path.normpath(dest), round(len(js) / 1e3), "KB")
    # the centre sites (with the air they dig: pits, doorways) and the drowned city's towers
    sites = {sid: export(make(), air=True) for sid, make in HK.SITE_BUILDERS.items()}
    towers = [export(HK.leaning_tower(*t)) for t in HK.TOWERS]
    for sid, d in sites.items(): print(sid, "cells", sum(r[3] for r in d["rows"]), "box", d["box"])
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "undertow", "sites_data.js")
    js = ("// Generated by map/structures/export_hollow.py from hollow_kit.py. Do not edit by hand.\n"
          "// The Hollow's centre sites and the drowned city's towers: palette [id, logical props], rows [y, z, x0, count, palette index].\n"
          "export const SITE_DESIGNS = " + json.dumps(sites, separators=(",", ":")) + ";\n"
          "export const TOWER_DESIGNS = " + json.dumps(towers, separators=(",", ":")) + ";\n")
    open(dest, "w").write(js)
    print("wrote", os.path.normpath(dest), round(len(js) / 1e3), "KB")
    if problems: print("PROBLEMS:\n  " + "\n  ".join(problems)); sys.exit(1)

if __name__ == "__main__":
    main()
