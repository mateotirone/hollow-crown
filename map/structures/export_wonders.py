"""Write the six wonders into the add-on.

    python3 export_wonders.py        -> ../../Siege_Nights_BP/scripts/wonders/designs_data.js
                                        + wonders/<id>/scene.json (for the 3D asset viewer)

Each wonder is a minecraft-builder spec in wonders/<id>.json (the one building engine). Same data shape as
export_halls.py: palette [id, logical props], rows [y, z, x0, count, palette index], local frame with the
front (the spec's south, +z) toward the origin side (local z flipped), lowest layer at y 0. Each wonder is
cut into six stages of about equal block count from the ground up (stages = first y of stages 2 to 6).
"""
import os, sys, json, subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SKILL = os.path.join(ROOT, ".claude", "skills", "minecraft-builder", "scripts", "build.py")
OUT_JS = os.path.join(ROOT, "Siege_Nights_BP", "scripts", "wonders", "designs_data.js")
IDS = ["great_lighthouse", "high_watch", "rimeforge_hall", "sun_gate", "lantern_spire", "great_horse_fair"]
SPEC = {"great_horse_fair": "horse_fair"}
KEEP = {"facing", "half", "axis", "hanging", "upper", "hinge", "open"}
STAGES = 6

def export(scene):
    ys = [b[1] for b in scene["blocks"]]; y0 = min(ys)
    pal, idx, cells = [], {}, {}
    for x, y, z, i in scene["blocks"]:
        n, p = scene["palette"][i]
        q = {k: v for k, v in p.items() if k in KEEP}
        key = json.dumps([n, q], sort_keys=True)
        if key not in idx: idx[key] = len(pal); pal.append([n if ":" in n else "minecraft:" + n, q])
        cells[(x, y - y0, -z)] = idx[key]
    rows = []
    for (y, z) in sorted({(c[1], c[2]) for c in cells}):
        run = None
        for x in sorted(c[0] for c in cells if c[1] == y and c[2] == z):
            pi = cells[(x, y, z)]
            if run and run[2] + run[3] == x and run[4] == pi: run[3] += 1
            else:
                if run: rows.append(run)
                run = [y, z, x, 1, pi]
        if run: rows.append(run)
    # stage cuts: the first y of each later stage, so each stage holds about a sixth of the blocks
    per_y = {}
    for (x, y, z) in cells: per_y[y] = per_y.get(y, 0) + 1
    total, acc, cuts = len(cells), 0, []
    for y in sorted(per_y):
        if len(cuts) < STAGES - 1 and acc >= total * (len(cuts) + 1) / STAGES: cuts.append(y)
        acc += per_y[y]
    while len(cuts) < STAGES - 1: cuts.append(max(per_y) + 1 + len(cuts))
    xs = [c[0] for c in cells]; zs = [c[2] for c in cells]
    box = {"x0": min(xs), "x1": max(xs), "z0": min(zs), "z1": max(zs), "y1": max(per_y)}
    return {"palette": pal, "rows": rows, "stages": cuts, "box": box, "blocks": total}

def main():
    out = {}
    for wid in IDS:
        spec = os.path.join(HERE, "wonders", f"{SPEC.get(wid, wid)}.json")
        od = os.path.join(HERE, "wonders", "out", wid)
        r = subprocess.run([sys.executable, SKILL, spec, od], capture_output=True, text=True)
        if r.returncode: sys.exit(f"{wid}: {r.stderr[-400:]}")
        d = export(json.load(open(os.path.join(od, "scene.json"))))
        b = d["box"]
        assert all(abs(v) <= 17 for v in (b["x0"], b["x1"], b["z0"], b["z1"])), f"{wid} is wider than 35: {b}"
        out[wid] = d
        print(wid, d["blocks"], "blocks, box", b, "stages from y", d["stages"])
    with open(OUT_JS, "w") as f:
        f.write("// Generated by map/structures/export_wonders.py from map/structures/wonders/*.json (minecraft-builder specs). Do not edit by hand.\n")
        f.write("// Each wonder: palette [id, logical props], rows [y, z, x0, count, palette index] (front toward -z), stages = first y of stages 2-6.\n")
        f.write("export const WONDER_DESIGNS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("wrote", OUT_JS, os.path.getsize(OUT_JS), "bytes")

if __name__ == "__main__":
    main()
