"""Write the Hollow's stronghold (hollow_stronghold.py) into the add-on as data the game stamps tile by tile.

    python3 export_stronghold.py     -> ../../Siege_Nights_BP/scripts/undertow/stronghold_data.js

Same row format as export_hollow.py (world offsets from the stronghold's middle, y = 0 the ground layer, the
air it digs included), kept in its own file because it is big (about 1.5 MB) and the game stamps it in tiles
(undertow/builder.js strongholdTick), never in one go. Names the design gives without a namespace that are
the add-on's own blocks get "siege:" here.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import hollow_stronghold as HS
from export_hollow import export

OWN = {"hollowwood_lattice", "hollowwood_core", "hollowwood_planks", "veinstone", "veinstone_bricks", "pale_ash",
       "glimbulb", "glimmerflow", "undertow_moss", "veilcap", "veilcap_cap", "veilcap_stem", "veilmoss_strands"}

def main():
    h = HS.build()
    bp = h.bp
    for k, (n, p) in list(bp.cells.items()):
        if n in OWN: bp.cells[k] = ("siege:" + n, p)
    d = export(bp, air=True)
    d["site"] = HS.SITE
    d["v"] = 1
    cells = sum(r[3] for r in d["rows"])
    print("stronghold cells", cells, "rows", len(d["rows"]), "palette", len(d["palette"]), "box", d["box"],
          "rooms", len(h.rooms), "furnished", h.furnished)
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "undertow", "stronghold_data.js")
    js = ("// Generated by map/structures/export_stronghold.py from hollow_stronghold.py. Do not edit by hand.\n"
          "// The stronghold west of the Long Climb: palette [id, logical props], rows [y, z, x0, count, palette index],\n"
          "// world offsets from its middle (site), y = 0 the ground layer.\n"
          "export const STRONGHOLD_DESIGN = " + json.dumps(d, separators=(",", ":")) + ";\n")
    open(dest, "w").write(js)
    print("wrote", os.path.normpath(dest), round(len(js) / 1e3), "KB")

if __name__ == "__main__":
    main()
