"""Write the Mason's Yard (review/specs/mason_yard_<region>.json, written by review/specs/gen_mason.py) into the add-on.

    python3 export_mason.py     -> ../../Siege_Nights_BP/scripts/settle/mason_data.js

Built on the building skill's engine (one engine), in the plot buildings' frame and data shape (export_halls.py):
the front row's middle is at (0, ?, 1), +z into the yard, y = 0 the ground course. Mark "bench" is where the game
sets the Mason's Bench (settle/masonyard.js); the mason stands in front of it.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
SKILL = os.path.join(HERE, "..", "..", ".claude", "skills", "minecraft-builder", "scripts")
if SKILL not in sys.path: sys.path.insert(0, SKILL)
from bp import Blueprint
from export_halls import export
import engine

REGIONS = ("vale", "frostmarch", "saltreach", "emberwaste", "blackfen")
SPECS = os.path.join(HERE, "review", "specs")

def build(region):
    spec = json.load(open(os.path.join(SPECS, f"mason_yard_{region}.json")))
    bp = Blueprint(spec["name"]); engine.into_blueprint(bp, spec)
    bp.marks = {k: tuple(v) for k, v in spec.get("marks", {}).items()}
    bp.markers["door"] = (0, 1, 0)
    return bp.finish() if hasattr(bp, "finish") else bp

def main():
    out, problems = {}, []
    for region in REGIONS:
        d = export(build(region)); b = d["box"]; out[region] = d
        if b["x1"] - b["x0"] + 1 > 9 or b["z1"] - b["z0"] + 1 > 9 or b["z0"] < 1: problems.append(f"{region}: box {b} is not inside 9 x 9")
        if "bench" not in d["marks"]: problems.append(f"{region}: no bench mark")
        print(region, "cells", sum(r[3] for r in d["rows"]), "box", b, "bench", d["marks"].get("bench"))
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "settle", "mason_data.js")
    open(dest, "w").write("// Generated by map/structures/export_mason.py from review/specs/mason_yard_<region>.json. Do not edit by hand.\n"
                          "// The Mason's Yard in each region's style, same shape as designs_data.js (front middle at z = 1, +z inward).\n"
                          "export const MASON_DESIGNS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(dest))
    if problems: print("PROBLEMS:\n  " + "\n  ".join(problems)); sys.exit(1)

if __name__ == "__main__":
    main()
