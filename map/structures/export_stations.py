"""Write the railway stations (four stages), Trade House wings and engine sheds, in each region's style.

    python3 export_stations.py   -> ../../Siege_Nights_BP/scripts/settle/station_data.js

Frame and limits are in stations.py. Checks: nothing (not even air) in local z -6..1 at y 0..4; no track
blocks; each stage inside its footprint and containing the stage before; the marks the train thread needs.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import stations as ST
from export_halls import export

NEED = {"track_centre", "platform_edge", "post", "stalls", "trade_join"}

def cells(d):
    for y, z, x0, n, i in d["rows"]:
        for x in range(x0, x0 + n): yield x, y, z, d["palette"][i][0]

def main():
    out = {"stations": {}, "trade": {}, "sheds": {}}
    problems = []
    for region in ST.REGIONS:
        out["stations"][region] = {}; out["trade"][region] = {}
        prev = None
        for stage in ST.STAGES:
            d = export(ST.STAGE_BUILDERS[stage](region)); b = d["box"]
            length, _, depth = ST.SIZE[stage]; half = length // 2
            for x, y, z, n in cells(d):
                if -6 <= z <= 1 and 0 <= y <= 4 and not (stage == "grand" and z == -7):
                    problems.append(f"{region} {stage}: {n} in the track zone at {x},{y},{z}"); break
                if "track" in n or n.endswith(":rail"): problems.append(f"{region} {stage}: places track {n}"); break
                if abs(x) > half or z > depth: problems.append(f"{region} {stage}: {n} outside the footprint at {x},{y},{z}"); break
                if z < 2 and y < 5 and not (stage == "grand" and z == -7): problems.append(f"{region} {stage}: {n} in front of the platform at {x},{y},{z}"); break
            if NEED - set(d["marks"]): problems.append(f"{region} {stage}: missing marks {sorted(NEED - set(d['marks']))}")
            if prev and not (b["x0"] <= prev["x0"] and b["x1"] >= prev["x1"] and b["z1"] >= prev["z1"]):
                problems.append(f"{region} {stage} does not contain the stage before")
            prev = b
            out["stations"][region][stage] = d
            print(region, stage, "cells", sum(r[3] for r in d["rows"]), "box", b, "join", d["marks"]["trade_join"])
            t = export(ST.trade_house(region, stage)); tb = t["box"]
            if max(-tb["x0"], tb["x1"]) > 5 or tb["z0"] < 0 or tb["z1"] > 8: problems.append(f"{region} trade {stage}: box {tb}")
            out["trade"][region][stage] = t
        s = export(ST.engine_shed(region)); sb = s["box"]
        for x, y, z, n in cells(s):
            if -2 <= z <= 2 and y == 0: problems.append(f"{region} shed: {n} on the track bed at {x},{y},{z}"); break
            if -2 <= z <= 2 and 1 <= y <= 4 and n != "minecraft:air": problems.append(f"{region} shed: {n} in the way at {x},{y},{z}"); break
        out["sheds"][region] = s
        print(region, "shed box", sb)
    dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "settle", "station_data.js")
    js = ("// Generated by map/structures/export_stations.py from stations.py. Do not edit by hand.\n"
          "// Railway stations in each region's style. Local frame: the main line runs along x at z = 0, x = 0 mid-platform,\n"
          "// the building behind at +z, the platform the y = 0 layer from z = 2. Nothing in z -6..1 at y 0..4; no track.\n"
          "// STATION_DESIGNS[region][halt|station|junction|grand]: marks track_centre, platform_edge, post, stalls, trade_join.\n"
          "// TRADE_HOUSE_DESIGNS[region][stage]: its (0, 0, 0) goes on the station's trade_join mark.\n"
          "// ENGINE_SHED_DESIGNS[region]: its own track along x at z = 0, inside z -2..2 clear to y 5.\n"
          "// Same shape as designs_data.js: palette [id, logical props], rows [y, z, x0, count, palette index]; draw with townhall/designs.js drawData.\n"
          "export const STATION_DESIGNS = " + json.dumps(out["stations"], separators=(",", ":")) + ";\n"
          "export const TRADE_HOUSE_DESIGNS = " + json.dumps(out["trade"], separators=(",", ":")) + ";\n"
          "export const ENGINE_SHED_DESIGNS = " + json.dumps(out["sheds"], separators=(",", ":")) + ";\n")
    open(dest, "w").write(js)
    print("wrote", os.path.normpath(dest), round(len(js) / 1e3), "KB")
    if problems: print("PROBLEMS:\n  " + "\n  ".join(problems[:40])); sys.exit(1)

if __name__ == "__main__":
    main()
