"""Write the material-loop machines (the Ironworks; the Gold Sluice and Deep Shaft follow the same way) into the
add-on, for the town's Works plots (Mateo 2026-11-12: the town generator makes the plots, the player picks a plot
and the machine builds itself there).

    python3 export_machines.py        -> ../../Siege_Nights_BP/scripts/ironworks/designs_data.js

The designs are the building skill's (ironworks/spec.py, every region's look). Same data shape and frame as
export_halls.py: the plot's front row is z = 0 (left clear; the yard's fence stands on row 1), +z into the plot, x = 0 the middle of the plot's front, y = 0 the
plot's ground. Stage 1 is the whole plot (fence, greenery on the ground not built yet); stages 2 and 3 hold only
what changes from the stage before (new blocks, and air where a tree or a fence goes), so an upgrade never
rebuilds what stands. "top" is the full height at that stage, "dig" how far the pit and the race go down.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
SKILL = os.path.join(HERE, "..", "..", ".claude", "skills", "minecraft-builder", "scripts")
if SKILL not in sys.path: sys.path.insert(0, SKILL)
from bp import Blueprint
from export_halls import export, KEEP

REGIONS = ("vale", "frostmarch", "saltreach", "emberwaste", "blackfen")
WIDE, DEEP = 27, 17                     # the Works plot (towngen_settle.py SHAPES "W"): the 25 x 15 yard and a block all round for the eaves
# machine -> (spec module dir, the machine's block, where it stands in the spec frame, the plot box x0 z0 x1 z1)
MACHINES = {
    "ironworks": dict(dir="ironworks", block="siege:ironworks", at=(-3, 1, -10), plot=(-17, -15, 7, -1)),
}


def blueprints(machine, region):
    """The three stages as finished Blueprints in the spec's frame, the machine's block in the yard"""
    import engine, importlib.util
    m = MACHINES[machine]
    path = os.path.join(HERE, m["dir"], "spec.py")
    s = importlib.util.spec_from_file_location(f"{machine}_spec", path); mod = importlib.util.module_from_spec(s); s.loader.exec_module(mod)
    specs = mod.specs(False, os.path.join(SKILL, ".."), (region,))
    out = []
    for lv in (1, 2, 3):
        bp = Blueprint(f"{machine}_{region}_{lv}"); bp.marks = {}
        engine.into_blueprint(bp, specs[f"{machine}_{region}_{lv}"])
        x, y, z = m["at"]
        bp.cells[(x, y, z)] = (m["block"], {})
        bp.marks["works"] = (x, y, z)
        x0, z0, x1, z1 = m["plot"]
        bp.markers["door"] = ((x0 + x1) // 2, 1, z1)      # the yard's front fence is row z = 1; row 0 is the plot's front margin
        out.append(bp.finish())
    return out


def cells_of(d):
    return {(x, y, z): i for y, z, x0, n, i in d["rows"] for x in range(x0, x0 + n)}


def rows_of(cells):
    rows, run = [], None
    for (y, z, x) in sorted((y, z, x) for (x, y, z) in cells):
        i = cells[(x, y, z)]
        if run and run[0] == y and run[1] == z and run[2] + run[3] == x and run[4] == i: run[3] += 1
        else:
            if run: rows.append(run)
            run = [y, z, x, 1, i]
    if run: rows.append(run)
    return rows


def stages(machine, region):
    """[stage 1 whole, stage 2 changes, stage 3 changes], one palette for the three"""
    pal, index, out, before = [], {}, [], {}
    def pi(entry):
        k = json.dumps(entry, sort_keys=True)
        if k not in index: index[k] = len(pal); pal.append(entry)
        return index[k]
    air = pi(["minecraft:air", {}])
    problems = []
    for lv, bp in enumerate(blueprints(machine, region), 1):
        d = export(bp)
        now = {c: pi(d["palette"][i]) for c, i in cells_of(d).items()}
        b = d["box"]
        if max(-b["x0"], b["x1"]) > WIDE // 2 or b["z0"] < 1 or b["z1"] > DEEP - 1:
            problems.append(f"{machine} {region} {lv}: outside the {WIDE} x {DEEP} Works plot {b}")
        change = {c: i for c, i in now.items() if before.get(c) != i}
        change.update({c: air for c in before if c not in now})     # a tree or fence the new stage takes away
        ys = [c[1] for c in now]
        out.append({"rows": rows_of(change), "box": b, "top": max(ys), "dig": -min(ys), "marks": d["marks"]})
        before = now
    return {"palette": pal, "stages": out}, problems


def main():
    problems = []
    for machine in MACHINES:
        data = {}
        for region in REGIONS:
            data[region], bad = stages(machine, region); problems += bad
            for lv, s in enumerate(data[region]["stages"], 1):
                print(machine, region, lv, "cells", sum(r[3] for r in s["rows"]), "box", s["box"], "top", s["top"], "dig", s["dig"])
        dest = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", machine, "designs_data.js")
        js = ("// Generated by map/structures/export_machines.py from " + MACHINES[machine]["dir"] + "/spec.py (the building skill). Do not edit by hand.\n"
              "// Per region: one palette [id, logical props] and three stages. Stage 1 is the whole Works plot; 2 and 3 hold only\n"
              "// what changes. rows [y, z, x0, count, palette index], the plot's front row at z = 0, x = 0 its middle.\n"
              "export const WORKS_DESIGNS = " + json.dumps(data, separators=(",", ":")) + ";\n")
        open(dest, "w").write(js)
        print("wrote", os.path.normpath(dest), round(len(js) / 1e3), "KB")
    if problems: print("PROBLEMS:\n  " + "\n  ".join(problems)); sys.exit(1)


if __name__ == "__main__":
    main()
