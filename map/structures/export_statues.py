"""Gather every statue-spot list (map/statue-spots/*.json, written by faceless_statues.write_spots or a town bake) into
the game's list, Siege_Nights_BP/scripts/statues/spots_data.js.

    python3 map/structures/export_statues.py
"""
import glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from faceless_statues import SPOTS_DIR, check_spot

OUT = os.path.join(HERE, "..", "..", "Siege_Nights_BP", "scripts", "statues", "spots_data.js")


def main():
    spots, seen = [], set()
    for path in sorted(glob.glob(os.path.join(SPOTS_DIR, "*.json"))):
        site = os.path.splitext(os.path.basename(path))[0]
        for s in json.load(open(path)):
            bad = check_spot(s)
            if s.get("id") in seen: bad.append("id used twice")
            if bad: raise SystemExit(f"{site} {s.get('id')}: {', '.join(bad)}")
            seen.add(s["id"]); spots.append({"site": site, **s})
    rows = ",\n".join("  " + json.dumps(s, separators=(",", ":")) for s in spots)
    open(OUT, "w").write("// Generated by map/structures/export_statues.py from map/statue-spots/*.json. Do not edit by hand.\n"
                         "// One entry per Faceless statue the game stands in the world (format: map/structures/faceless_statues.py).\n"
                         f"export const SPOTS = [\n{rows},\n];\n")
    print(len(spots), "statue spots ->", os.path.relpath(OUT))


if __name__ == "__main__":
    main()
