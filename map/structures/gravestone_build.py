"""The Gravestone: what a fallen player leaves behind, built with the minecraft-builder skill.

Mateo's design (2026-11-12): when a player dies their things go into a gravestone where they fell. It stays
sealed to everyone but them for a while; a player-killed player's grave is open to anyone at once.

The build is small on purpose (it appears anywhere, in any region, so it is region-neutral and borrows no
region's palette): a 3 x 3 footprint, odd both ways. The headstone (siege:gravestone, the block you click)
stands at the back centre facing out over a 1 x 2 mound of pale moss; a single candle burns on its left while
the grave is sealed and goes out when it opens to everyone; a tuft of dry grass on its right.

    python3 map/structures/gravestone_build.py OUT          -> OUT/gravestone/scene.json (+ .mcfunction) for the viewer
    python3 map/structures/gravestone_build.py --export     -> Siege_Nights_BP/scripts/graves/design_data.js

The game frame: (0, 0, 0) is the headstone, standing on the ground (y = 0 is the first air layer), +z is the
way it faces. The game only places a part where the cell is free (air or a plant) and, for the soft parts,
where there is solid ground under it; the headstone always goes in.
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
BUILD = os.path.join(ROOT, ".claude", "skills", "minecraft-builder", "scripts", "build.py")
DATA = os.path.join(ROOT, "Siege_Nights_BP", "scripts", "graves", "design_data.js")

# [x, y, z, block, props, role]; role: "stone" (the headstone), "candle" (lit while sealed), "soft" (decor)
PARTS = [
    [0, 0, 0, "siege:gravestone", {"facing": "s"}, "stone"],
    [0, 0, 1, "pale_moss_carpet", {}, "soft"],
    [0, 0, 2, "pale_moss_carpet", {}, "soft"],
    [-1, 0, 0, "candle", {"lit": True}, "candle"],
    [1, 0, 0, "short_dry_grass", {}, "soft"],
]


def spec():
    return {"name": "gravestone", "edition": "bedrock", "materials": {},
            "place": [[x, y, z, b, p] for x, y, z, b, p, _ in PARTS]}


def export():
    lines = [
        "// Generated by map/structures/gravestone_build.py. Do not edit by hand.",
        "// The Gravestone: [x, y, z, block id, role]. (0, 0, 0) is the headstone on the ground, +z the way it faces.",
        "// Roles: stone = the headstone (siege:gravestone), candle = lit while sealed, soft = decor that needs ground.",
        "export const GRAVE_PARTS = " + json.dumps([[x, y, z, b if ":" in b else "minecraft:" + b, r] for x, y, z, b, _, r in PARTS]) + ";",
        "",
    ]
    os.makedirs(os.path.dirname(DATA), exist_ok=True)
    open(DATA, "w").write("\n".join(lines))
    print("wrote", os.path.relpath(DATA, ROOT))


def main():
    if "--export" in sys.argv: return export()
    out = os.path.abspath(sys.argv[1])
    d = os.path.join(out, "gravestone")
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "spec.json")
    json.dump(spec(), open(path, "w"))
    extra = [] if "--preview" in sys.argv else ["--no-preview"]
    if "--hifi" in sys.argv:
        i = sys.argv.index("--hifi"); extra += ["--hifi", sys.argv[i + 1], sys.argv[i + 2], "--shots", "front-left,front-right,high,back"]
    subprocess.run([sys.executable, BUILD, path, d] + extra, check=True, stdout=subprocess.DEVNULL)
    print("gravestone ok")


if __name__ == "__main__":
    main()
