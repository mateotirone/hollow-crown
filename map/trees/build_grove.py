"""The Forester's Lodge grove: the region trees a settlement may grow and fell, in normal breakable wood.

    python3 map/trees/build_grove.py [--preview OUT --textures T --three X]     (run from the repo root)

Writes, for each settlement style, three species x three stages (sapling, young, mature) x two variants:
    Siege_Nights_BP/structures/siege_grove/<species>_<stage>_<v>.mcstructure   (placed as "siege_grove:<name>")
    Siege_Nights_BP/scripts/forestry/grove_data.js                            (offsets, wood cells, block types)
The grove trees are NOT locked (lock.py): they are the one place trees can be chopped. Ground cells (y = 0)
are left out, the yard lays its own soil. --preview renders a level-3 grove per style into OUT.
"""
import argparse, json, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", "structures"))
from species import CARDS
from grow import grow
from bp import Blueprint

# Three species a settlement can grow, by settlement style. Chosen for useful, different woods.
GROVE = {
    "vale": ["vale_great_oak", "vale_ash", "vale_silver_birch"],
    "frostmarch": ["frost_tall_spruce", "frost_scots_pine", "frost_snow_birch"],
    "saltreach": ["salt_umbrella_pine", "salt_olive", "salt_italian_cypress"],
    "emberwaste": ["ember_date_palm", "ember_umbrella_acacia", "ember_baobab"],
    "blackfen": ["fen_bald_cypress", "fen_pollard_willow", "fen_black_alder"],
}
STAGES = ["sapling", "young", "mature"]
VARIANTS = 2
PITCH, COLS, ROWS = 13, 3, 2            # plots: 3 across, 2 deep, 13 apart (odd yard: 41 x 29)
GROUND = {"dirt_with_roots", "coarse_dirt", "podzol", "rooted_dirt", "mud", "sand", "grass_block", "moss_block", "mangrove_roots", "muddy_mangrove_roots", "dirt"}


def is_wood(n): return n.endswith("_log") or n.endswith("_wood") or n.startswith("siege:hollowwood")


def drop_of(n):
    """The item a felled wood cell gives: bark-all-round wood comes back as its log."""
    if n.startswith("siege:"): return n
    if n.endswith("_wood"): n = n[:-5] + "_log"
    return "minecraft:" + n


def plots():
    """Plot centres in the lodge frame: the block at (0, 1, 0), +z runs into the yard. Order = unlock order."""
    out = []
    for r in range(ROWS):
        for c in (1, 0, 2):
            out.append([(c - 1) * PITCH, 8 + r * PITCH])
    return out


def tree(sid, stage, v):
    t = grow(CARDS[sid], stage, 7000 + sum(map(ord, sid)) * 10 + STAGES.index(stage) * 3 + v)
    for cell in [c for c, (n, p) in t.cells.items() if c[1] <= 0 and (n in GROUND or c[1] < 0)]: del t.cells[cell]
    for cell in [c for c, (n, p) in t.cells.items() if c[1] <= 0]: del t.cells[cell]
    t.rotations = [0]
    return t


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--preview", default=""); ap.add_argument("--textures", default=""); ap.add_argument("--three", default="")
    a = ap.parse_args()
    sdir = os.path.join("Siege_Nights_BP", "structures", "siege_grove"); os.makedirs(sdir, exist_ok=True)
    designs, species = {}, {}
    for style, sids in GROVE.items():
        for sid in sids:
            woods = set()
            for stage in STAGES:
                for v in range(VARIANTS):
                    t = tree(sid, stage, v); name = f"{sid}_{stage}_{v}"
                    t.save_mcstructure(os.path.join(sdir, name + ".mcstructure"))
                    lo, hi = t.bounds()
                    types = sorted({t.to_bedrock(n, p)[0] for n, p in t.cells.values()})
                    wood = [[x, y, z] for (x, y, z), (n, p) in sorted(t.cells.items()) if is_wood(n)]
                    drops = {}
                    for (n, p) in t.cells.values():
                        if is_wood(n): drops[drop_of(n)] = drops.get(drop_of(n), 0) + 1; woods.add(drop_of(n))
                    designs[name] = {"lo": list(lo), "hi": list(hi), "types": types, "wood": wood, "drops": drops}
            species[sid] = {"name": CARDS[sid]["name"], "woods": sorted(woods)}
    js = os.path.join("Siege_Nights_BP", "scripts", "forestry", "grove_data.js"); os.makedirs(os.path.dirname(js), exist_ok=True)
    with open(js, "w") as f:
        f.write("// Generated by map/trees/build_grove.py. Do not edit by hand.\n")
        f.write("// Grove trees for the Forester's Lodge, placed as structures \"siege_grove:<design>\". Coordinates are\n")
        f.write("// relative to the trunk's ground cell (the trunk starts one above it). lo/hi: the structure's corners.\n")
        f.write("// wood: the cells that are logs (what a felled tree gives back). types: every block type in it.\n")
        f.write(f"export const GROVE = {json.dumps(GROVE)};\n")
        f.write(f"export const GROVE_STAGES = {json.dumps(STAGES)};\nexport const GROVE_VARIANTS = {VARIANTS};\n")
        f.write(f"export const GROVE_PLOTS = {json.dumps(plots())};\n")
        f.write(f"export const GROVE_SPECIES = {json.dumps(species)};\n")
        f.write(f"export const GROVE_DESIGNS = {json.dumps(designs, separators=(',', ':'))};\n")
    print("designs", len(designs))
    if not a.preview: return
    for style, sids in GROVE.items():
        yard = Blueprint(f"grove_{style}")
        x0, x1, z0, z1 = -20, 20, 1, 29
        for x in range(x0, x1 + 1):
            for z in range(z0 - 3, z1 + 1): yard.set(x, 0, z, "grass_block")
        for x in range(x0, x1 + 1):
            for z in (z0, z1):
                if not (z == z0 and -1 <= x <= 1): yard.set(x, 1, z, "spruce_fence")
        for z in range(z0, z1 + 1):
            for x in (x0, x1): yard.set(x, 1, z, "spruce_fence")
        yard.set(0, 1, 0, "barrel")
        for i, (px, pz) in enumerate(plots()):
            for dx in range(-2, 3):
                for dz in range(-2, 3): yard.set(px + dx, 0, pz + dz, "podzol" if abs(dx) + abs(dz) < 4 else "coarse_dirt")
            stage = "mature" if i < 4 else ("young" if i == 4 else "sapling")
            t = tree(sids[i % 3], stage, i % VARIANTS); yard.paste(t, px, 0, pz)
        yard.finish() if hasattr(yard, "finish") else None
        pd = os.path.join(a.preview, style); os.makedirs(pd, exist_ok=True); yard.save_logical(os.path.join(pd, "scene.json"))
        subprocess.run([sys.executable, os.path.join(HERE, "..", "structures", "render", "render.py"), os.path.join(pd, "scene.json"), pd,
                        "--title", f"Forester's Lodge grove ({style})", "--blurb", "Level 3: six plots. Back row: a young tree and a sapling regrowing after felling.",
                        "--textures", a.textures, "--three", a.three, "--shots", "front-left,high"], check=True)


if __name__ == "__main__":
    main()
