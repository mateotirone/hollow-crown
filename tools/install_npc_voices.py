#!/usr/bin/env python3
"""Install the story characters' spoken greetings.

The words are hand-written in Siege_Nights_BP/scripts/lore/data/dialogue.js and mentors.js. ElevenLabs reads them in
the voice Mateo picked for each character (studio/voices/npc_cast.json); Mateo checks the takes on the listening page.
This script levels each take, converts it to the .ogg Minecraft wants, wires it into sound_definitions.json as
siege.voice.<npc>.<node>_<variant>, and writes Siege_Nights_BP/scripts/lore/data/npc_voices.js. When a character opens
a scene whose words have a recording, lore/npcs.js plays it to that player from the character.

Takes are named <npc>_<node>_<variant>.mp3 (variant 0 is the node's own text, 1 and up its greets, in order).

  python3 tools/install_npc_voices.py --takes DIR          every take in DIR
  python3 tools/install_npc_voices.py wren_hub_2=take.mp3  one line from any file (a redo)
  python3 tools/install_npc_voices.py --status             which characters have recordings
  python3 tools/install_npc_voices.py --remove wren_hub_2  back to words only

A take whose words no longer match the dialogue (the line was rewritten) is refused: record it again.
Needs ffmpeg and node.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RP = os.path.join(ROOT, "Siege_Nights_RP")
DEFS = os.path.join(RP, "sounds/sound_definitions.json")
RECORD = os.path.join(ROOT, "studio/voices/npc_installed.json")
OUT_JS = os.path.join(ROOT, "Siege_Nights_BP/scripts/lore/data/npc_voices.js")
SOUND_DIR = "sounds/siege/voice"
LEVEL = ("silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
         "silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-17:TP=-1.5")

LIST_LINES = r"""
const root = process.argv[1];
const { NPCS } = await import(root + "/dialogue.js");
const M = await import(root + "/mentors.js");
const seen = new Set(), out = [];
for (const list of [NPCS, ...Object.values(M).filter((v) => Array.isArray(v) && v[0]?.nodes)])
  for (const n of list) for (const [node, x] of Object.entries(n.nodes)) if (x.greets?.length)
    [x.text, ...x.greets].forEach((text, v) => { const k = `${n.id}_${node}_${v}`; if (!seen.has(k)) { seen.add(k); out.push({ key: k, npc: n.id, node, v, text }); } });
console.log(JSON.stringify(out));
"""

def load(path, default):
    return json.load(open(path, encoding="utf8")) if os.path.exists(path) else default

def save(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf8") as f:
        json.dump(data, f, indent=1, ensure_ascii=False); f.write("\n")

def lines():
    data = os.path.join(ROOT, "Siege_Nights_BP/scripts/lore/data")
    out = subprocess.run(["node", "--input-type=module", "-e", LIST_LINES, "file://" + data], capture_output=True, text=True, check=True).stdout
    return {l["key"]: l for l in json.loads(out)}

sound_id = lambda l: f"siege.voice.{l['npc']}.{l['node']}_{l['v']}"
sound_path = lambda l: f"{SOUND_DIR}/{l['npc']}/{l['node']}_{l['v']}"

def duration(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path], capture_output=True, text=True).stdout.strip()
    try: return round(float(out), 2)
    except ValueError: return 0.0

def install(l, src):
    dst = os.path.join(RP, sound_path(l) + ".ogg")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", src, "-af", LEVEL, "-ac", "1", "-ar", "44100",
                    "-c:a", "libvorbis", "-q:a", "4", dst], check=True, timeout=120)
    return duration(dst)

def write(table, record):
    d = load(DEFS, {"format_version": "1.14.0", "sound_definitions": {}})
    defs = d["sound_definitions"]
    for k in [k for k in defs if k.startswith("siege.voice.") and k.count(".") == 3 and k.split(".")[2] in {l["npc"] for l in table.values()}]:
        if k not in {sound_id(table[r]) for r in record if r in table}: del defs[k]
    for key in record:
        l = table[key]
        defs[sound_id(l)] = {"category": "neutral", "max_distance": 16,
                             "sounds": [{"name": sound_path(l), "volume": 1.0, "load_on_low_memory": True}]}
    save(DEFS, d)
    body = "".join(f'  "{table[k]["npc"]}/{table[k]["node"]}/{table[k]["v"]}": {{ id: "{sound_id(table[k])}", text: {json.dumps(table[k]["text"])}, seconds: {record[k]["seconds"]} }},\n'
                   for k in sorted(record))
    with open(OUT_JS, "w", encoding="utf8") as f:
        f.write("// GENERATED by tools/install_npc_voices.py. Do not edit by hand.\n"
                "// Story characters' spoken greetings: \"npc/node/variant\" -> the recording and the exact words it reads.\n"
                "// lore/npcs.js plays one only while its words still match the dialogue, so a rewritten line goes quiet.\n"
                "export const NPC_VOICES = {" + ("\n" + body if body else "") + "};\n")

def main(argv):
    table, record = lines(), load(RECORD, {})
    for k in list(record):  # drop recordings of lines that were rewritten or removed
        if k not in table or record[k]["text"] != table[k]["text"]:
            print(f"dropped {k}: its words changed, record it again"); del record[k]
    if "--status" in argv:
        by = {}
        for l in table.values(): by.setdefault(l["npc"], [0, 0])[1] += 1
        for k in record: by[table[k]["npc"]][0] += 1
        for npc, (have, want) in sorted(by.items()): print(f"  {npc:10} {have:3} of {want:3} lines voiced")
        return
    if "--remove" in argv:
        k = argv[argv.index("--remove") + 1]
        if k in record:
            try: os.remove(os.path.join(RP, sound_path(table[k]) + ".ogg"))
            except OSError: pass
            del record[k]
    jobs = []
    if "--takes" in argv:
        folder = argv[argv.index("--takes") + 1]
        for f in sorted(os.listdir(folder)):
            k = os.path.splitext(f)[0]
            if k in table: jobs.append((k, os.path.join(folder, f)))
    for a in argv:
        if "=" in a and not a.startswith("--"):
            k, src = a.split("=", 1)
            if k not in table: sys.exit(f"{k} is not a greeting line (npc_node_variant)")
            jobs.append((k, src))
    for k, src in jobs:
        secs = install(table[k], src)
        record[k] = {"text": table[k]["text"], "seconds": secs, "source": os.path.basename(src)}
        print(f"  {k:28} {secs:5.2f} s")
    save(RECORD, dict(sorted(record.items())))
    write(table, record)
    print(f"{len(record)} of {len(table)} greeting lines voiced. Next: node tools/check.mjs")

if __name__ == "__main__":
    main(sys.argv[1:])
