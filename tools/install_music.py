#!/usr/bin/env python3
"""Install soundtrack pieces into the game.

Each piece has a name the soundtrack knows (Siege_Nights_BP/scripts/music/data.js: vale_theme, vale_night,
boss_bride, siege_night, main_theme ...). This script levels it to a gentle music loudness, encodes it as a
streamed stereo .ogg (Siege_Nights_RP/sounds/siege/music/<name>.ogg), defines siege.music.<name> with category
music (so Minecraft's own Music slider sets its volume) and writes Siege_Nights_BP/scripts/music/installed.js.

  python3 tools/install_music.py vale_theme=/path/song.mp3 ...   install pieces
  python3 tools/install_music.py --status                        what is installed
  python3 tools/install_music.py --remove vale_day               take one out

Needs ffmpeg.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RP = os.path.join(ROOT, "Siege_Nights_RP")
DEFS = os.path.join(RP, "sounds/sound_definitions.json")
OUT_JS = os.path.join(ROOT, "Siege_Nights_BP/scripts/music/installed.js")
DATA_JS = os.path.join(ROOT, "Siege_Nights_BP/scripts/music/data.js")
SOUND_DIR = "sounds/siege/music"
VANILLA_GAME_MUSIC = ["music.game", "music.game.creative", "music.game.water", "music.overworld.deep_dark"]  # the menu keeps its own
LEVEL = "loudnorm=I=-20:TP=-2,afade=t=in:d=1.5"

def load(path, default):
    return json.load(open(path, encoding="utf8")) if os.path.exists(path) else default

def save(path, data):
    with open(path, "w", encoding="utf8") as f:
        json.dump(data, f, indent=1, ensure_ascii=False); f.write("\n")

def known():
    """Every piece name data.js mentions."""
    src = open(DATA_JS, encoding="utf8").read()
    return set(re.findall(r'"([a-z]+_[a-z_]+)"', src)) - {"siege_music"}

def duration(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path], capture_output=True, text=True).stdout.strip()
    try: return round(float(out), 1)
    except ValueError: return 0.0

def installed():
    d = load(DEFS, {"sound_definitions": {}})["sound_definitions"]
    out = {}
    for k in sorted(d):
        if k.startswith("siege.music."):
            path = os.path.join(RP, d[k]["sounds"][0]["name"] + ".ogg")
            if os.path.exists(path): out[k] = duration(path)
    return out

def write_js():
    have = installed()
    body = "".join(f'  "{k}": {{ seconds: {v} }},\n' for k, v in have.items())
    with open(OUT_JS, "w", encoding="utf8") as f:
        f.write("// GENERATED by tools/install_music.py. Do not edit by hand.\n"
                "// The soundtrack pieces installed in the resource pack, with their length in seconds. music/index.js skips any\n"
                "// piece that is not listed here.\n"
                "export const INSTALLED_MUSIC = {" + ("\n" + body if body else "") + "};\n")
    return have

def main(argv):
    names = known()
    if "--status" in argv:
        have = installed()
        for n in sorted(names): print(f"  {'installed' if 'siege.music.' + n in have else 'missing  '}  {n}")
        return
    d = load(DEFS, {"format_version": "1.14.0", "sound_definitions": {}})
    defs = d["sound_definitions"]
    if "--remove" in argv:
        n = argv[argv.index("--remove") + 1]
        defs.pop("siege.music." + n, None)
        try: os.remove(os.path.join(RP, SOUND_DIR, n + ".ogg"))
        except OSError: pass
    for a in argv:
        if "=" not in a or a.startswith("--"): continue
        n, src = a.split("=", 1)
        if n not in names: sys.exit(f"{n} is not a piece the soundtrack knows (see music/data.js)")
        dst = os.path.join(RP, SOUND_DIR, n + ".ogg")
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", src, "-af", LEVEL, "-ac", "2", "-ar", "44100",
                        "-c:a", "libvorbis", "-q:a", "0", dst], check=True, timeout=300)
        defs["siege.music." + n] = {"category": "music", "min_distance": 1000, "max_distance": 10000,
                                    "sounds": [{"name": f"{SOUND_DIR}/{n}", "stream": True, "volume": 0.8, "load_on_low_memory": True}]}
        print(f"  {n:22} {duration(dst):6.1f} s  {os.path.getsize(dst) / 1e6:4.1f} MB")
    if any(k.startswith("siege.music.") for k in defs):  # Minecraft's own game music would play over ours: silence it
        quiet = os.path.join(RP, SOUND_DIR, "silence.ogg")
        if not os.path.exists(quiet):
            subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=44100:cl=mono", "-t", "1",
                            "-c:a", "libvorbis", quiet], check=True)
        for vanilla in VANILLA_GAME_MUSIC:
            defs[vanilla] = {"category": "music", "sounds": [{"name": f"{SOUND_DIR}/silence", "stream": True}]}
    save(DEFS, d)
    have = write_js()
    print(f"{len(have)} pieces installed. Next: node tools/check.mjs")

if __name__ == "__main__":
    main(sys.argv[1:])
