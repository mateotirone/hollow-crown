"""Export the Hollow's tree species (map/trees, PR #94) for the Hollow terrain generator.

    python3 tools/hollow_trees.py

Grows Latticewood, Veilmoss Tree and Ashen Deadwood at three sizes, several variants each, makes them
unbreakable like every other world tree (map/trees/lock.py), and writes
Siege_Nights_BP/scripts/undertow/trees_data.js: per tree a palette of [Bedrock id, Bedrock states] and
vertical runs [x, z, y0, y1, palette index] as offsets from the trunk's ground cell (y = 0 is the
ground surface, the tree stands on it from y = 1). The generator turns each run into one fill.
Rerun after changing those species in map/trees/species.py.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "map", "trees"))
from species import CARDS          # noqa: E402
from grow import grow              # noqa: E402
from lock import locked            # noqa: E402

SPECIES = ["hollow_latticewood", "hollow_veilmoss_tree", "hollow_ash_dead"]
SIZES = ["young", "mature", "ancient"]
VARIANTS = 4
OUT = os.path.join(ROOT, "Siege_Nights_BP", "scripts", "undertow", "trees_data.js")


def runs_of(bp):
    pal, idx, cols = [], {}, {}
    for (x, y, z), (n, p) in bp.cells.items():
        if y < 0: continue
        name, st = bp.to_bedrock(n, p)
        key = json.dumps([name, st], sort_keys=True)
        if key not in idx: idx[key] = len(pal); pal.append([name, st])
        cols.setdefault((x, z), []).append((y, idx[key]))
    runs = []
    for (x, z), cells in sorted(cols.items()):
        cells.sort()
        y0, prev_y, prev_i = cells[0][0], cells[0][0], cells[0][1]
        for y, i in cells[1:] + [(None, None)]:
            if y is not None and y == prev_y + 1 and i == prev_i:
                prev_y = y
                continue
            runs.append([x, z, y0, prev_y, prev_i])
            if y is not None: y0, prev_y, prev_i = y, y, i
    return pal, runs


def main():
    trees = {}
    total = 0
    for sid in SPECIES:
        card = CARDS[sid]
        trees[sid] = {}
        for size in SIZES:
            out = []
            for v in range(VARIANTS):
                seed = sum(map(ord, sid)) * 1000 + 500 + SIZES.index(size) * 100 + v   # not the database's seeds: new shapes
                t = locked(grow(card, size, seed))
                pal, runs = runs_of(t)
                xs = [r[0] for r in runs]; zs = [r[1] for r in runs]
                reach = max(max(map(abs, xs)), max(map(abs, zs)))
                height = max(r[3] for r in runs)
                out.append({"palette": pal, "runs": runs, "reach": reach, "height": height})
                total += len(runs)
            trees[sid][size] = out
    with open(OUT, "w") as f:
        f.write("// Generated by tools/hollow_trees.py from map/trees (the Hollow's species). Do not edit by hand.\n")
        f.write("// HOLLOW_TREES[species][size] = [{ palette: [[id, states]], runs: [[x, z, y0, y1, palette index]], reach, height }]\n")
        f.write("// Offsets from the trunk's ground cell; y = 0 is the ground surface.\n")
        f.write("export const HOLLOW_TREES = " + json.dumps(trees, separators=(",", ":")) + ";\n")
    print(f"{len(SPECIES)} species x {len(SIZES)} sizes x {VARIANTS} variants, {total} runs, {os.path.getsize(OUT) // 1024} KB -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
