#!/usr/bin/env node
// Lists every clock mount (siege:clock_anchor) baked into the map file, so the living clocks (scripts/clocks) know
// where to stand. Mounts that scripts place in game announce themselves; only the baked ones need listing.
//
//   node tools/clock_spots.mjs          -> Siege_Nights_BP/scripts/clocks/spots_data.js
//   node tools/clock_spots.mjs --check  exit 1 when spots_data.js is out of date (tools/check.mjs runs this)
//
// Reads map/*-blocks.json (the towns genworld stamps; world coordinates).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "Siege_Nights_BP/scripts/clocks/spots_data.js");
const MOUNT = "siege:clock_anchor";

export function bakedSpots() {
  const spots = [];
  for (const f of readdirSync(join(ROOT, "map")).filter((n) => n.endsWith("-blocks.json")).sort()) {
    const d = JSON.parse(readFileSync(join(ROOT, "map", f), "utf8"));
    const mounts = new Set((d.palette ?? []).map((e, i) => (e.name === MOUNT ? i : -1)).filter((i) => i >= 0));
    if (!mounts.size) continue;
    for (const [x, y, z, p] of d.blocks ?? []) if (mounts.has(p)) spots.push([x, y, z]);
  }
  return spots.sort((a, b) => a[0] - b[0] || a[2] - b[2] || a[1] - b[1]);
}

export function spotsFile(spots) {
  return "// Generated by tools/clock_spots.mjs. Do not edit by hand.\n"
    + "// Clock mounts (siege:clock_anchor) baked into the map file (map/*-blocks.json), as [x, y, z] in the overworld.\n"
    + "// Mounts that scripts place (the Reeve's square, plot buildings, the showcase) announce themselves instead.\n"
    + `export const SPOTS = ${JSON.stringify(spots)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = spotsFile(bakedSpots());
  if (process.argv.includes("--check")) {
    const now = readFileSync(OUT, "utf8");
    if (now !== text) { console.log("clocks/spots_data.js is out of date: run node tools/clock_spots.mjs"); process.exit(1); }
    console.log("clock spots up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
