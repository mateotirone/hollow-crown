#!/usr/bin/env node
// Writes map/structures/stages.json from settle/config.js STAGES, for the town generator (towngen_settle.py
// charter()): the buildings each settlement stage must build and the plot classes each may take, so a map rebuild
// lays the plots every stage needs. Run after changing STAGES or a plot size:   node tools/export_stages.mjs
// --check: exit 1 if the file is out of date (tools/check.mjs runs this).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "map/structures/stages.json");
const C = await import(pathToFileURL(join(ROOT, "Siege_Nights_BP/scripts/settle/config.js")).href);

// The generator's classes: S, M, MF (a Medium by the fields), ML, L, LD (a deep Large, 15 x 17), G, W (Works yard)
function classes(id) {
  if (id === "farmhouse") return ["MF"]; // the Farmhouse stands by its field (towngen FARM_EDGE)
  let cs = [C.PLOT_SIZE[id] ?? "S", ...(C.PLOT_ALSO[id] ?? [])];
  if (C.PLOT_MIN_BOX[id]) cs = cs.map((c) => (c === "L" ? "LD" : c));
  if (cs.includes("M")) cs.push("MF");
  return [...new Set(cs)];
}
const data = {
  note: "Generated by tools/export_stages.mjs from Siege_Nights_BP/scripts/settle/config.js STAGES. Do not edit by hand.",
  homes: ["S", "M", "MF", "ML"],
  stages: C.STAGES.map((s) => ({
    tier: s.tier, name: s.name, homes: s.homes ?? 0,
    build: s.build.filter((b) => !b.pending).map((b) => ({ id: b.id, classes: classes(b.id), ...(b.region ? { region: b.region } : {}) })),
    pending: s.build.filter((b) => b.pending).map((b) => b.id),
  })),
};
const text = JSON.stringify(data, null, 1) + "\n";
if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) { console.log("map/structures/stages.json is out of date: run node tools/export_stages.mjs"); process.exit(1); }
} else { writeFileSync(OUT, text); console.log(`wrote ${OUT}`); }
