#!/usr/bin/env python3
"""The Hamlet wall drawn in tight round the starter village (Mateo, 2026-11-14: "dead space" in the Hamlet).

    python3 tools/export_hamlet_walls.py SDIR     -> Siege_Nights_BP/scripts/settle/hamlet_walls_data.js
        SDIR holds the starter villages (<plot>.json, format hollow-crown-starter/1, from map/structures/starter_all.py)

The starter's wall outline (radii) is at least WALL_BASE (36) out all the way round, plus slow lobes, so where the
village has nothing on one side the Low Palisade bulged round empty grass. Here the Hamlet ring keeps only what it
holds: at each of the outline's angles, KEEP blocks past the furthest planned cell (paths, plots, yards, the hall's
ground) on that side, never less than LEAST. It is smoothed the same way, and keeps the starter's own line across the
gate. The Town, City and Castle rings keep the full outline (walldata.js radiusAt uses these radii only for the
Hamlet ring), so nothing the later tiers plan for is lost.
"""
import json, math, os, sys, glob

KEEP = 5        # the wall stays this far outside anything planned (as starter.py: room for the walk, the steps and the reserve)
LEAST = 22      # never closer than this to the square
SPAN, NOTCH = 3, 3   # outline points either side a dip is measured over, and how deep it may go (no sharp notches)
GATE_KEEP = 6   # outline points either side of the gate that keep the starter's line (the gate chord)

def tight(st):
    radii = st["wall"]["radii"]; N = len(radii)
    pts = [(math.atan2(dz, dx), math.hypot(dx, dz)) for dx, dz, kind, _ in st["used"] if not (kind == 3 and math.hypot(dx, dz) >= 20)]
    # the line KEEP blocks out from everything planned: along each ray, the furthest point of a KEEP-wide disc round any
    # planned cell (an exact offset of the village, so the wall hugs the corners of plots instead of bulging past them)
    need = []
    for i in range(N):
        a = i / N * 2 * math.pi; ca, sa = math.cos(a), math.sin(a)
        far = 0
        for b, d in pts:
            along, perp = d * math.cos(b - a), abs(d * math.sin(b - a))
            if along > 0 and perp <= KEEP: far = max(far, along + math.sqrt(KEEP * KEEP - perp * perp))
        need.append(far)
    # no sharp notches between two plots: a dip narrower than about 20 degrees is filled to within NOTCH of its sides
    r = [max(LEAST, n, max(need[(i + d) % N] for d in range(-SPAN, SPAN + 1)) - NOTCH) for i, n in enumerate(need)]
    for _ in range(2):
        r = [max((r[i - 1] + 2 * r[i] + r[(i + 1) % N]) / 4, need[i]) for i in range(N)]
    gi = round((st["wall"]["gateAngle"] % (2 * math.pi)) / (2 * math.pi) * N) % N
    for d in range(-GATE_KEEP, GATE_KEEP + 1): r[(gi + d) % N] = radii[(gi + d) % N]
    return [round(min(v, radii[i]), 1) for i, v in enumerate(r)]   # never further out than the starter's own line

def main(sdir):
    out = {}
    for path in sorted(glob.glob(os.path.join(sdir, "*.json"))):
        st = json.load(open(path))
        if st.get("format") != "hollow-crown-starter/1": continue
        key = st["plot"].lower(); out[key] = tight(st)
        print(f"{key}: wall {min(st['wall']['radii']):.0f}-{max(st['wall']['radii']):.0f} -> {min(out[key]):.0f}-{max(out[key]):.0f}")
    dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "Siege_Nights_BP", "scripts", "settle", "hamlet_walls_data.js")
    with open(dest, "w") as f:
        f.write("// Generated by tools/export_hamlet_walls.py from the starter villages. Do not edit by hand.\n")
        f.write("// The Hamlet ring drawn tight round each starter village: radii at the same even angles as towns_data.js outline.radii.\n")
        f.write("export const HAMLET_WALLS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("wrote", dest)

if __name__ == "__main__":
    main(sys.argv[1])
