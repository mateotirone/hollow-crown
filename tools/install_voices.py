#!/usr/bin/env python3
"""Install Morvane's spoken lines into the game.

The words are in studio/voices/morvane.json (hand-written). ElevenLabs reads them; Mateo picks a voice and
takes on the listening page. This script gives each picked take the in-game treatment for where it is heard
(far = a voice with no speaker, before the Rift; mid = in the Hollow; dry = in the fight), converts it to the
.ogg Minecraft wants, wires it into sound_definitions.json as siege.voice.morvane.<id>, and writes
Siege_Nights_BP/scripts/lore/data/morvane_lines.js, which the game reads (lore/morvane_voice.js).

  python3 tools/install_voices.py --takes DIR --voice b       every line from DIR/<id>_b.mp3 (raw, untreated takes)
  python3 tools/install_voices.py fall_4=/some/take.mp3       one line from any file (a redo)
  python3 tools/install_voices.py                             only rewrite morvane_lines.js from the json
  python3 tools/install_voices.py --status                    which lines have a recording

Without a recording a line still shows its words in chat; it just isn't heard. Needs ffmpeg.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RP = os.path.join(ROOT, "Siege_Nights_RP")
DEFS = os.path.join(RP, "sounds/sound_definitions.json")
LINES = os.path.join(ROOT, "studio/voices/morvane.json")
OUT_JS = os.path.join(ROOT, "Siege_Nights_BP/scripts/lore/data/morvane_lines.js")
SOUND_DIR = "sounds/siege/voice/morvane"
PREFIX = "siege.voice.morvane."

TRIM = ("silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
        "silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.3,")
FX = {
    "far": "highpass=f=140,lowpass=f=3800,aecho=0.8:0.7:60|130:0.35|0.2,loudnorm=I=-20:TP=-2",
    "mid": "highpass=f=90,aecho=0.8:0.8:40|90:0.2|0.1,loudnorm=I=-18:TP=-2",
    "dry": "loudnorm=I=-16:TP=-1.5",
}
VOLUME = {"far": 0.8, "mid": 0.9, "dry": 1.0}

def load(path):
    with open(path, encoding="utf8") as f:
        return json.load(f)

def save(path, data):
    with open(path, "w", encoding="utf8") as f:
        json.dump(data, f, indent=1, ensure_ascii=False); f.write("\n")

def duration(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                         capture_output=True, text=True).stdout.strip()
    try: return round(float(out), 2)
    except ValueError: return 0.0

def ogg_of(line_id):
    return os.path.join(RP, SOUND_DIR, f"{line_id}.ogg")

def install(line, src):
    dst = ogg_of(line["id"])
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-af", TRIM + FX[line["fx"]],
                    "-ac", "1", "-ar", "44100", "-c:a", "libvorbis", "-q:a", "5", dst], check=True)
    print(f"  {line['id']:<16} {duration(dst):>5.2f} s  ({line['fx']})  from {os.path.basename(src)}")

def wire(lines):
    defs = load(DEFS)
    sd = defs["sound_definitions"]
    for k in [k for k in sd if k.startswith(PREFIX)]:
        del sd[k]
    for l in lines:
        if os.path.exists(ogg_of(l["id"])):
            sd[PREFIX + l["id"]] = {"category": "ui", "sounds": [{"name": f"{SOUND_DIR}/{l['id']}", "volume": VOLUME[l["fx"]], "load_on_low_memory": True}]}
    save(DEFS, defs)

def write_js(data):
    rows = []
    for l in data["lines"]:
        ogg = ogg_of(l["id"])
        secs = duration(ogg) if os.path.exists(ogg) else 0
        rows.append({"id": l["id"], "text": l["text"], "fx": l["fx"], "seconds": secs})
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    js = ("// GENERATED by tools/install_voices.py from studio/voices/morvane.json. Do not edit by hand.\n"
          "// Morvane's spoken lines. seconds = 0: no recording installed yet (the words still show in chat).\n"
          f"export const VOICE_PREFIX = {json.dumps(PREFIX)};\n"
          f"export const MORVANE_LINES = [\n{body},\n];\n")
    with open(OUT_JS, "w", encoding="utf8") as f:
        f.write(js)

def main(argv):
    data = load(LINES)
    lines = data["lines"]
    by_id = {l["id"]: l for l in lines}
    if "--status" in argv:
        for l in lines:
            print(f"  {'heard ' if os.path.exists(ogg_of(l['id'])) else 'words '} {l['id']}")
        return
    takes = voice = None
    picks = {}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--takes": takes = argv[i + 1]; i += 2; continue
        if a == "--voice": voice = argv[i + 1].lower(); i += 2; continue
        if "=" in a:
            k, v = a.split("=", 1)
            if k not in by_id: sys.exit(f"no line called {k} in {LINES}")
            picks[k] = v
        else:
            sys.exit(__doc__)
        i += 1
    if takes:
        if not voice: sys.exit("--takes needs --voice a|b|c")
        for l in lines:
            src = os.path.join(takes, f"{l['id']}_{voice}.mp3")
            if l["id"] not in picks and os.path.exists(src): picks[l["id"]] = src
    for k, src in picks.items():
        if not os.path.exists(src): sys.exit(f"missing {src}")
        install(by_id[k], src)
    wire(lines)
    write_js(data)
    have = sum(os.path.exists(ogg_of(l["id"])) for l in lines)
    print(f"{have} of {len(lines)} lines have a recording. Wrote {os.path.relpath(OUT_JS, ROOT)}.")

if __name__ == "__main__":
    main(sys.argv[1:])
