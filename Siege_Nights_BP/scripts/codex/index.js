const ENTRIES = entries();
const BY_ID = Object.fromEntries(ENTRIES.map((e) => [e.id, e]));
const TOTAL = ENTRIES.length;
export const CHAPTER_TITLE = {
  regions: "Armourer of the Five", oathsworn: "Oath-Bearer", mythical: "Finder of Lost Things", relics: "Trophy-Taker",
  wonders: "Choirsmith", caravan: "Friend of the Caravans", charms: "Walker of Thin Places", keepsakes: "Keeper of Small Things",
};
const BOOK_TITLE = "Keeper of the Codex";
const pic = (id, found) => `textures/ui/codex/${short(id)}${found ? "" : "_outline"}`;
const show = (form, p) => form.show(p).catch(() => ({ canceled: true }));

// ---------- finding ----------
function record(p, ids) {
  const rec = foundOf(p);
  const fresh = ids.map(short).filter((s) => isEntry(`siege:${s}`) && !rec.f.includes(s));
  if (!fresh.length) return [];
  const before = rec.f.length;
  const day = world.getDay();
  for (const s of fresh) { rec.f.push(s); rec.d[s] = day; rec.n.push(s); }
  const after = rec.f.length;
  rec.t ??= [];
  const has = new Set(rec.f.map((s) => `siege:${s}`));
  const newTitles = [];
  for (const c of chapterCounts(has)) {
    const t = CHAPTER_TITLE[c.id];
    if (c.total && c.found === c.total && t && !rec.t.includes(t)) { rec.t.push(t); newTitles.push(t); }
  }
  if (after >= TOTAL && !rec.t.includes(BOOK_TITLE)) { rec.t.push(BOOK_TITLE); newTitles.push(BOOK_TITLE); }
  saveFound(p);
  for (const s of fresh) {
    const e = BY_ID[`siege:${s}`];
    p.onScreenDisplay.setActionBar(`§6New in your Codex: §f${e?.name ?? s}`);
  }
  sfx(p, "random.toast");
  for (const n of milestonesFor(before, after)) {
    pay(p, CODEX.milestoneRegals, "codex");
    p.sendMessage(`§6Codex: ${n} entries.§7 The Kingsrest clerks send ${CODEX.milestoneRegals} Regals for your trouble.`);
  }
  for (const t of newTitles) {
    p.onScreenDisplay.setTitle(`§6${t}`, { subtitle: "§7a new title in your Codex", fadeInDuration: 10, stayDuration: 60, fadeOutDuration: 20 });
    sfx(p, "random.levelup");
    world.sendMessage(`§6${p.name}§7 is now §6${t}§7.`);
  }
  emit("codexFound", { player: p, ids: fresh.map((s) => `siege:${s}`), total: after });
  return fresh;
}
export const markFound = (p, ids) => record(p, ids);

function scan() {
  for (const p of players()) {
    let mode;
    try { mode = p.getGameMode(); } catch { continue; }
    if (mode === GameMode.Creative || mode === GameMode.Spectator) continue; // creative players can take anything from the menu
    const seen = new Set();
    try {
      const inv = p.getComponent("inventory")?.container;
      for (let i = 0; inv && i < inv.size; i++) {
        const t = inv.getItem(i)?.typeId;
        if (t && isEntry(t)) seen.add(t);
      }
      const eq = p.getComponent("equippable");
      for (const s of SLOTS) {
        const t = eq?.getEquipment(s)?.typeId;
        if (t && isEntry(t)) seen.add(t);
      }
    } catch {
      continue;
    }
    if (seen.size) record(p, [...seen]);
  }
}
onTick("codex:scan", CODEX.scanTicks, scan);
world.afterEvents.playerLeave.subscribe((e) => forgetLive(e.playerId));

// ---------- the book ----------
function bar(n, total, width = 20) {
  const full = total ? Math.round((n / total) * width) : 0;
  return `§6${"|".repeat(full)}§8${"|".repeat(width - full)}`;
}

export async function openCodex(p) {
  const rec = foundOf(p);
  const has = new Set(rec.f.map((s) => `siege:${s}`));
  const counts = chapterCounts(has);
  const fresh = new Set(rec.n);
  const found = counts.reduce((a, c) => a + c.found, 0);
  const next = (Math.floor(found / CODEX.milestoneEvery) + 1) * CODEX.milestoneEvery;
  const form = new ActionFormData().title("The Codex").body([
    `§7Every rare thing in the realm, set down by the Kingsrest clerks. What you have held, they draw in full. What you haven't, only its shape, and what the clerks heard about it.`,
    `§f${found} of ${TOTAL} found\n${bar(found, TOTAL)}`,
    found < TOTAL ? `§7Next reward at ${next}: ${CODEX.milestoneRegals} Regals.` : "§6Every page is filled.",
    rec.t?.length ? `§7Titles: §6${rec.t.join("§7, §6")}` : "",
  ].filter(Boolean).join("\n\n"));
  const shown = counts.filter((c) => c.total);
  for (const c of shown) {
    const list = ENTRIES.filter((e) => e.chapter === c.id);
    const newHere = list.some((e) => fresh.has(short(e.id)));
    const first = list.find((e) => has.has(e.id)) ?? list[0];
    form.button(`${newHere ? "§a● §r" : ""}${c.name}\n§8${c.found} of ${c.total}${c.found === c.total ? "  §6complete" : ""}`, pic(first.id, has.has(first.id)));
  }
  form.button("Close");
  const r = await show(form, p);
  if (r.canceled || r.selection >= shown.length) return;
  return chapterPage(p, shown[r.selection].id);
}

async function chapterPage(p, chapterId) {
  const rec = foundOf(p);
  const has = new Set(rec.f);
  const list = ENTRIES.filter((e) => e.chapter === chapterId);
  const ch = CHAPTERS.find((c) => c.id === chapterId);
  const n = list.filter((e) => has.has(short(e.id))).length;
  const form = new ActionFormData().title(ch?.name ?? "The Codex").body(`§f${n} of ${list.length} found\n${bar(n, list.length)}`);
  for (const e of list) {
    const got = has.has(short(e.id));
    const isNew = rec.n.includes(short(e.id));
    form.button(got ? `${isNew ? "§a● §r" : ""}${e.mythical || chapterId === "mythical" ? "§6" : ""}${e.name}` : "§8? ? ?", pic(e.id, got));
  }
  form.button("Back");
  const r = await show(form, p);
  if (r.canceled) return;
  if (r.selection >= list.length) return openCodex(p);
  return entryPage(p, list[r.selection], chapterId);
}

async function entryPage(p, e, chapterId) {
  const rec = foundOf(p);
  const s = short(e.id);
  const got = rec.f.includes(s);
  if (got && rec.n.includes(s)) { rec.n = rec.n.filter((x) => x !== s); saveFound(p); }
  const lines = got
    ? [
      e.does ? `§f${e.does}` : "",
      e.line ? `§o§7"${e.line}"§r` : "",
      e.region ? `§7Belongs to §f${e.region}§7. It only answers to those who live there, or carry a ${e.region} Kin-Writ.` : "",
      e.price ? `§7${e.price} Regals at the caravan market, when it's on the stalls.` : "",
      `§8${e.source ?? ""}${rec.d[s] !== undefined ? `  Found on day ${rec.d[s]}.` : ""}`,
    ]
    : ["§7Not found yet.", `§f${e.hint ?? "The clerks know nothing about it."}`];
  const form = new ActionFormData().title(got ? e.name : "? ? ?").body(lines.filter(Boolean).join("\n\n"));
  form.button(got ? e.name : "Not found yet", pic(e.id, got));
  form.button("Back");
  const r = await show(form, p);
  if (!r.canceled) return chapterPage(p, chapterId);
}

// Open it from the book, the Keep menu or the command
world.afterEvents.itemUse.subscribe((ev) => {
  if (ev.itemStack?.typeId !== CODEX.bookId || ev.source?.typeId !== "minecraft:player") return;
  system.run(() => openCodex(ev.source));
});
addKeepMenuButtons(({ player }) => [{ label: "The Codex", action: () => openCodex(player) }]);
system.beforeEvents.startup.subscribe((e) => {
  const registry = e.customCommandRegistry;
  if (!registry?.registerCommand) return;
  registry.registerCommand(
    { name: "siege:codex", description: "Open your Codex", permissionLevel: CommandPermissionLevel.Any, cheatsRequired: false },
    (origin) => {
      const player = origin.sourceEntity;
      if (!player || player.typeId !== "minecraft:player") return { status: CustomCommandStatus.Failure, message: "Only a player has a Codex." };
      system.run(() => { try { openCodex(player); } catch { /* left meanwhile */ } });
      return { status: CustomCommandStatus.Success };
    },
  );
});

// A new player gets the book
addJoinStep(36, "codex book", async (player, { wait }) => {
  give(player, CODEX.bookId, 1);
  player.sendMessage("§6The Codex§7 is in your pack: a book of rare things. Anything rare you pick up gets drawn in it. Use it, or type /siege:codex.");
  await wait(20);
}, { when: "first" });

// ---------- test tools ----------
system.afterEvents.scriptEventReceive.subscribe((e) => {
  if (e.id !== "siege:codex") return;
  const p = e.sourceEntity?.typeId === "minecraft:player" ? e.sourceEntity : undefined;
  if (!p) return;
  if (!isCreative(p)) return p.sendMessage("§7The Codex test tools are for creative mode.");
  const [cmd, arg] = e.message.trim().split(/\s+/);
  if (cmd === "all") { record(p, ENTRIES.map((x) => x.id)); return p.sendMessage(`§7Codex: all ${TOTAL} entries marked found.`); }
  if (cmd === "reset") {
    const rec = foundOf(p); rec.f = []; rec.d = {}; rec.n = []; rec.t = []; saveFound(p); forgetGiven(p.id);
    return p.sendMessage("§7Codex: emptied, and every find can be found again.");
  }
  if (cmd === "give" && arg) {
    const id = arg.includes(":") ? arg : `siege:${arg}`;
    return give(p, id, 1) ? p.sendMessage(`§7Gave ${id}.`) : p.sendMessage(`§c${id} is not an item.`);
  }
  if (cmd === "forge" && arg) return emit("codexForge", { player: p, wonderId: arg });
  if (cmd === "caravan") return emit("codexCaravan", { player: p });
  if (cmd === "writs") return p.sendMessage(`§7Kin-Writs: ${JSON.stringify(store.data.writs)}`);
  system.run(() => openCodex(p));
});

// ---------- self-tests ----------
addTests("codex", {
  "every entry has a name, a chapter, a hint and a source": () => {
    for (const e of ENTRIES) assert(e.name && e.chapter && e.hint && (e.source || e.existing), `${e.id} is missing words`);
  },
  "no entry is in the book twice": () => assertEqual(new Set(ENTRIES.map((e) => e.id)).size, ENTRIES.length),
  "every chapter has entries and a title": () => {
    for (const c of CHAPTERS) {
      assert(ENTRIES.some((e) => e.chapter === c.id), `${c.id} is empty`);
      assert(CHAPTER_TITLE[c.id], `${c.id} has no title`);
    }
  },
  "milestones every ten": () => {
    assertEqual(milestonesFor(9, 10).join(), "10");
    assertEqual(milestonesFor(8, 31).join(), "10,20,30");
    assertEqual(milestonesFor(10, 19).length, 0);
  },
  "the region lock": () => {
    assert(mayWear("Frostmarch", "Frostmarch", {}, "a"), "home region");
    assert(!mayWear("Frostmarch", "Saltreach", {}, "a"), "other region");
    assert(mayWear("Frostmarch", "Saltreach", { Frostmarch: ["a"] }, "a"), "with a writ");
    assert(mayWear(undefined, undefined, {}, "a"), "no region");
    assertEqual([penaltyStage(0), penaltyStage(CODEX.warnSeconds), penaltyStage(CODEX.warnSeconds + CODEX.slowSeconds)].join(), "0,1,2");
  },
  "every forge recipe makes a real item from real things": () => {
    for (const w of ["rimeforge_hall", "high_watch", "great_lighthouse", "sun_gate", "lantern_spire", "great_horse_fair"]) {
      const list = forgeRecipes(w);
      assert(list.length, `${w} forges nothing`);
      for (const r of list) {
        assert(ITEM[r.out], `${w} makes ${r.out}, which is not a Codex item`);
        assert(r.cost?.length, `${r.out} costs nothing`);
      }
    }
    assertEqual(pricesFor(40, true), 80);
  },
  "the caravan shows four goods, the same all period": () => {
    const a = caravanStock(3), b = caravanStock(5);
    assertEqual(a.length, CODEX.caravanStall);
    assertEqual(a.map((g) => g.id).join(), b.map((g) => g.id).join());
    for (const g of a) assert(g.price > 0, `${g.id} has no price`);
  },
  "every set has four pieces": () => {
    for (const set of ["rimeforged", "watchward", "tidewrought", "sunscale", "fenlight", "oathsworn"]) {
      const ids = ["helmet", "chestplate", "leggings", "boots"].map((p) => `siege:${set}_${p}`);
      assertEqual(setCount(ids, set), 4, set);
    }
  },
  "every find is a Codex entry": () => {
    for (const s of SPOTS) assert(isEntry(s.id), `${s.id} is found somewhere but not in the book`);
    for (const [, [id]] of Object.entries(OATH_DROP)) assert(isEntry(id), `${id} drops but is not in the book`);
  },
});
