// The Codex: a book of every rare thing in the realm. What you have held shows in full; what you haven't shows its
// outline and a hint. Every ten finds pays 50 Regals; a whole chapter earns a title; the whole book, "Keeper of the Codex".
//
//   Open it: use the Codex (siege:codex), the Keep menu, or type /siege:codex
//   /scriptevent siege:codex all | reset | give <short id> | forge <wonderId> | caravan    (creative test tools)
//
// Files: rules.js (no Minecraft), state.js (saved data + helpers), powers.js (what the items do), forge.js (wonders'
// forges, Kin-Writs, the caravan market), finds.js (drops and places), items_data.js (generated by studio/build_codex.py).

